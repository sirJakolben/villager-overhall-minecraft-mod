/**
 * Draws the cannon and the mast of an upgraded boat (Obsidian Fisherman.md, 2026-10-12) inside Vanilla's boat renderer, in the boat's own model space
 * (mixin/AbstractBoatRendererMixin hooks in after the hull). The static parts come from the Blockbench model (BoatUpgradeModel, generated by
 * tools/bbmodel_to_boat_model.js): per frame only their baked quads go through the pose. The sail is Vanilla's own banner flag model, drawn
 * with the banner's colour and patterns by Vanilla's banner code, and placed where the model's flag cube is (turned 90 degrees, hanging from the yard).
 *
 * Coordinates: the model is in pixels with Y up and the bow towards -X, Y = 0 at the bottom of the hitbox; Vanilla's boat space is the model space
 * of BoatModel (pixels / 16, Y down, flipped about the hull's height) - USER_TO_BOAT converts. The renderer already applied the Y-flip and 90 degree
 * turn of Vanilla's boat when it calls submit.
 */
public final class BoatUpgradeRenderer {

    private static final Identifier SAIL_TEXTURE = texture("sail");
    private static final Identifier CANNON_TEXTURE = texture("cannon");
    private static final Identifier RAILINGS_TEXTURE = texture("railings");
    private static final Identifier DOUBLE_CHEST_TEXTURE = texture("double_chest");
    /** Texture ids of the model (BoatUpgradeModel): 0 is the boat's own wood. */
    private static final int WOOD_TEXTURE_ID = 0;
    private static final int SAIL_TEXTURE_ID = 1;
    private static final int CANNON_TEXTURE_ID = 2;
    private static final int RAILINGS_TEXTURE_ID = 3;
    private static final int DOUBLE_CHEST_TEXTURE_ID = 10;

    /** Vanilla's boat renders at 0.375 blocks (6 pixels) above the entity origin: user Y = 6 - boat Y. */
    private static final float HULL_OFFSET = 6.0F;

    private static final List<Quad> CANNON_QUADS = new ArrayList<>();
    private static final List<Quad> SAIL_QUADS = new ArrayList<>();
    private static final List<Quad> STERN_QUADS = new ArrayList<>();
    private static final List<Quad> DOUBLE_CHEST_QUADS = new ArrayList<>();

    static {
        bake(BoatUpgradeModel.CANNON, CANNON_QUADS);
        bake(BoatUpgradeModel.SAIL, SAIL_QUADS);
        bake(BoatUpgradeModel.STERN, STERN_QUADS);
        bakeDoubleChest(BoatUpgradeModel.DOUBLE_CHEST, DOUBLE_CHEST_QUADS);
    }

    /** Where the cannon, the sail and the stern sit in the model, along the boat in blocks: the front slot (cannon) and the rear slot (sail, stern) of a Vanilla boat. A boat with other slot positions shifts them. */
    private static final double CANNON_MODEL_OFFSET = 0.2;
    private static final double SAIL_MODEL_OFFSET = -0.6;
    private static final double STERN_MODEL_OFFSET = -0.6;
    /** A chest stands this much towards the bow of its slot (2 px - it was drawn too far back). The floor of the boat is at 3 px (Vanilla boat space, Y down). */
    private static final double CHEST_FORWARD = 2.0 / 16.0;
    private static final float FLOOR = 3.0F / 16.0F;
    /** The double chest stands 3 px further towards the bow than a single one (as placed by hand in the game, 2026-10-12). */
    private static final double DOUBLE_CHEST_FORWARD = 3.0 / 16.0;

    private final BannerFlagModel flagModel;
    private final SpriteGetter sprites;
    private final ModelPart chest;
    private final Identifier woodTexture;

    /** boatTexture is the renderer's own (textures/entity/boat/oak.png): the stern is made of that wood. Chests use Vanilla's normal chest. */
    public BoatUpgradeRenderer(EntityModelSet modelSet, SpriteGetter sprites, Identifier boatTexture) {
        this.flagModel = new BannerFlagModel(modelSet.bakeLayer(ModelLayers.STANDING_BANNER_FLAG));
        this.sprites = sprites;
        this.chest = BoatChestModel.bake();
        this.woodTexture = boatTexture;
    }

    /** Called inside the boat's pose; does nothing for a plain boat. */
    public void submit(BoatState state, double[] offsets, PoseStack poseStack, SubmitNodeCollector collector, int light, float ageInTicks) {
        if (state.filledSlots() == 0 && state.decos().isEmpty()) {
            return;
        }
        if (state.cannon()) {
            poseStack.pushPose();
            alongBoat(poseStack, slotOffset(offsets, 0) - CANNON_MODEL_OFFSET);
            submitQuads(CANNON_QUADS, poseStack, collector, light);
            poseStack.popPose();
        }
        // two chests in neighbouring slots are one double chest
        for (int slot = 0; slot < state.slots().size(); slot++) {
            if (!state.part(slot).equals(BoatParts.CHEST.id())) {
                continue;
            }
            if (state.part(slot + 1).equals(BoatParts.CHEST.id())) {
                poseStack.pushPose();
                alongBoat(poseStack, (slotOffset(offsets, slot) + slotOffset(offsets, slot + 1)) / 2.0 + CHEST_FORWARD + DOUBLE_CHEST_FORWARD);
                submitQuads(DOUBLE_CHEST_QUADS, poseStack, collector, light);
                poseStack.popPose();
                slot++;
            } else {
                submitChest(poseStack, collector, light, slotOffset(offsets, slot) + CHEST_FORWARD);
            }
        }
        if (state.sail()) {
            poseStack.pushPose();
            alongBoat(poseStack, slotOffset(offsets, state.sailSlot()) - SAIL_MODEL_OFFSET);
            submitQuads(SAIL_QUADS, poseStack, collector, light);
            if (state.hasBanner()) {
                submitFlag(state.banner(), poseStack, collector, light, ageInTicks);
            }
            poseStack.popPose();
        }
        if (state.stern()) {
            poseStack.pushPose();
            alongBoat(poseStack, slotOffset(offsets, offsets.length - 1) - STERN_MODEL_OFFSET);
            submitQuads(STERN_QUADS, poseStack, collector, light);
            poseStack.popPose();
        }
    }

    /**
     * The chest of Vanilla's chest boat (12 x 8 x 12 with a 4 px lid, 2 px smaller than a chest block), closed, standing on the boat's floor at this position along
     * it, lock towards the bow like in a chest boat - with the normal chest texture for now (Obsidian: Fehlende Texturen). Its parts are in block space with Y up and the
     * lock at +Z; the boat's space has Y down and the bow at +X - the half turn about Z (scale -1, -1, 1) puts the chest upright, the quarter turn about Y points the lock.
     */
    private void submitChest(PoseStack poseStack, SubmitNodeCollector collector, int light, double forward) {
        poseStack.pushPose();
        poseStack.translate((float) forward, FLOOR, 0.0F);
        poseStack.mulPose(Axis.YP.rotationDegrees(90.0F));
        poseStack.scale(-1.0F, -1.0F, 1.0F);
        poseStack.translate(-0.5F, 0.0F, -0.5F);
        collector.submitModelPart(chest, poseStack, BoatChestModel.SPRITE.renderType(RenderTypes::entityCutout), light, OverlayTexture.NO_OVERLAY, this.sprites.get(BoatChestModel.SPRITE));
        poseStack.popPose();
    }

    private static double slotOffset(double[] offsets, int slot) {
        return slot >= 0 && slot < offsets.length ? offsets[slot] : 0.0;
    }

    /** Moves everything that follows towards the bow by this many blocks - in Vanilla's boat space the bow is +X. */
    private static void alongBoat(PoseStack poseStack, double blocks) {
        poseStack.translate((float) blocks, 0.0F, 0.0F);
    }

    private Identifier textureOf(int id) {
        return switch (id) {
            case SAIL_TEXTURE_ID -> SAIL_TEXTURE;
            case CANNON_TEXTURE_ID -> CANNON_TEXTURE;
            case RAILINGS_TEXTURE_ID -> RAILINGS_TEXTURE;
            case DOUBLE_CHEST_TEXTURE_ID -> DOUBLE_CHEST_TEXTURE;
            default -> woodTexture;
        };
    }

    /** One draw call per texture the part uses. */
    private void submitQuads(List<Quad> all, PoseStack poseStack, SubmitNodeCollector collector, int light) {
        for (int textureId : all.stream().map(quad -> quad.texture).distinct().toList()) {
            List<Quad> quads = all.stream().filter(quad -> quad.texture == textureId).toList();
            if (!quads.isEmpty()) {
                collector.submitCustomGeometry(poseStack, RenderTypes.entityCutout(textureOf(textureId)), (pose, buffer) -> {
                    for (Quad quad : quads) {
                        quad.emit(pose, buffer, light);
                    }
                });
            }
        }
    }

    /** Vanilla's flag model placed on the model's flag cube (BoatUpgradeModel.FLAG), then Vanilla's own base and pattern layers. */
    private void submitFlag(ItemStack banner, PoseStack poseStack, SubmitNodeCollector collector, int light, float ageInTicks) {
        BoatUpgradeModel.Flag flag = BoatUpgradeModel.FLAG;
        DyeColor baseColor = banner.getItem() instanceof BannerItem item ? item.getColor() : DyeColor.WHITE;
        BannerPatternLayers patterns = banner.getOrDefault(DataComponents.BANNER_PATTERNS, BannerPatternLayers.EMPTY);
        float phase = (ageInTicks % 100.0F) / 100.0F;

        poseStack.pushPose();
        poseStack.translate(0.0F, HULL_OFFSET / 16.0F, 0.0F);
        poseStack.scale(-1.0F / 16.0F, -1.0F / 16.0F, 1.0F / 16.0F);
        pivot(poseStack, flag.groupOrigin(), flag.groupRotation());
        pivot(poseStack, flag.cubeOrigin(), flag.cubeRotation());
        // Vanilla's flag (its own model space: Y down, X flipped) onto the cube, then back to the block units its model parts expect.
        poseStack.translate(flag.shift()[0], flag.shift()[1], flag.shift()[2]);
        poseStack.scale(-1.0F, -1.0F, 1.0F);
        poseStack.scale(16.0F, 16.0F, 16.0F);
        collector.submitModel(this.flagModel, phase, poseStack, light, OverlayTexture.NO_OVERLAY, -1, Sheets.BANNER_BASE, this.sprites, 0, null);
        BannerRenderer.submitPatterns(this.sprites, poseStack, collector, light, OverlayTexture.NO_OVERLAY, this.flagModel, phase, true, baseColor, patterns, null);
        poseStack.popPose();
    }

    /** Rotation (degrees, Blockbench order) about a pivot, in the model's own pixels. */
    private static void pivot(PoseStack poseStack, float[] origin, float[] rotation) {
        poseStack.translate(origin[0], origin[1], origin[2]);
        poseStack.mulPose(new Quaternionf().rotationZYX((float) Math.toRadians(rotation[2]), (float) Math.toRadians(rotation[1]), (float) Math.toRadians(rotation[0])));
        poseStack.translate(-origin[0], -origin[1], -origin[2]);
    }

    private static Identifier texture(String name) {
        return Identifier.fromNamespaceAndPath(SmartVillagerProfessionsMod.MODID, "textures/entity/boat/" + name + ".png");
    }

    // ---- baking the Blockbench cubes into quads ----

    /** One face: four corners in boat space (blocks), the outward normal, the UV of each corner, and its texture. */
    private record Quad(int texture, Vector3f[] corners, Vector3f normal, float[] uv) {

        void emit(PoseStack.Pose pose, VertexConsumer buffer, int light) {
            Vector3f normalInWorld = pose.transformNormal(normal, new Vector3f());
            for (int i = 0; i < 4; i++) {
                Vector3f p = pose.pose().transformPosition(corners[i], new Vector3f());
                buffer.addVertex(p.x(), p.y(), p.z(), -1, uv[i * 2], uv[i * 2 + 1], OverlayTexture.NO_OVERLAY, light, normalInWorld.x(), normalInWorld.y(), normalInWorld.z());
            }
        }
    }

    /** The model's own space (pixels, Y up) into Vanilla's boat space (blocks, Y down). */
    private static Matrix4f toBoatSpace() {
        return new Matrix4f()
                .translate(0.0F, HULL_OFFSET / 16.0F, 0.0F)
                .scale(-1.0F / 16.0F, -1.0F / 16.0F, 1.0F / 16.0F);
    }

    /** Where Blockbench puts this cube in the model's space: its own rotation about its pivot, then its group's about the group's. */
    private static Matrix4f placeInModel(BoatUpgradeModel.Cube cube) {
        return new Matrix4f()
                .translate(cube.groupOrigin()[0], cube.groupOrigin()[1], cube.groupOrigin()[2])
                .rotateZYX((float) Math.toRadians(cube.groupRotation()[2]), (float) Math.toRadians(cube.groupRotation()[1]), (float) Math.toRadians(cube.groupRotation()[0]))
                .translate(-cube.groupOrigin()[0], -cube.groupOrigin()[1], -cube.groupOrigin()[2])
                .translate(cube.origin()[0], cube.origin()[1], cube.origin()[2])
                .rotateZYX((float) Math.toRadians(cube.rotation()[2]), (float) Math.toRadians(cube.rotation()[1]), (float) Math.toRadians(cube.rotation()[0]))
                .translate(-cube.origin()[0], -cube.origin()[1], -cube.origin()[2]);
    }

    private static void bake(BoatUpgradeModel.Cube[] cubes, List<Quad> into) {
        bake(cubes, into, new Matrix4f());
    }

    /** extra is applied in the model's space after the cubes are placed (the double chest uses it to be centred and turned). */
    private static void bake(BoatUpgradeModel.Cube[] cubes, List<Quad> into, Matrix4f extra) {
        for (BoatUpgradeModel.Cube cube : cubes) {
            Matrix4f matrix = toBoatSpace().mul(extra).mul(placeInModel(cube));
            for (int face = 0; face < 6; face++) {
                BoatUpgradeModel.Face uv = cube.faces()[face];
                if (uv != null) {
                    into.add(quad(matrix, cube.from(), cube.to(), face, uv));
                }
            }
        }
    }

    /**
     * The double chest as it was modelled (boats/chest_boat_doublechest.bbmodel: placed at the Vanilla chest's spot, long across the boat), moved to stand on the
     * floor with its middle at the origin and turned so that its long side lies along the boat - the lock then faces a side; BoatUpgradeRenderer puts it between two slots.
     */
    private static void bakeDoubleChest(BoatUpgradeModel.Cube[] cubes, List<Quad> into) {
        float minX = Float.MAX_VALUE;
        float maxX = -Float.MAX_VALUE;
        float minZ = Float.MAX_VALUE;
        float maxZ = -Float.MAX_VALUE;
        for (BoatUpgradeModel.Cube cube : cubes) {
            Matrix4f placed = placeInModel(cube);
            for (int corner = 0; corner < 8; corner++) {
                Vector3f p = placed.transformPosition(new Vector3f(
                        (corner & 1) == 0 ? cube.from()[0] : cube.to()[0], (corner & 2) == 0 ? cube.from()[1] : cube.to()[1], (corner & 4) == 0 ? cube.from()[2] : cube.to()[2]));
                minX = Math.min(minX, p.x);
                maxX = Math.max(maxX, p.x);
                minZ = Math.min(minZ, p.z);
                maxZ = Math.max(maxZ, p.z);
            }
        }
        float centreX = (minX + maxX) / 2.0F;
        float centreZ = (minZ + maxZ) / 2.0F;
        // the longer side of the box is turned onto the boat's length (user X)
        boolean longAlongZ = maxZ - minZ > maxX - minX;
        Matrix4f extra = new Matrix4f().rotateY((float) Math.toRadians(longAlongZ ? 90.0 : 0.0)).translate(-centreX, 0.0F, -centreZ);
        bake(cubes, into, extra);
    }

    /** Face order of BoatUpgradeModel: north, east, south, west, up, down. Corners: top-left, top-right, bottom-right, bottom-left as Blockbench's default UV sees the face from outside. */
    private static Quad quad(Matrix4f matrix, float[] from, float[] to, int face, BoatUpgradeModel.Face uv) {
        float x1 = from[0];
        float y1 = from[1];
        float z1 = from[2];
        float x2 = to[0];
        float y2 = to[1];
        float z2 = to[2];
        float[][] c = switch (face) {
            case 0 -> new float[][]{{x2, y2, z1}, {x1, y2, z1}, {x1, y1, z1}, {x2, y1, z1}};
            case 1 -> new float[][]{{x2, y2, z2}, {x2, y2, z1}, {x2, y1, z1}, {x2, y1, z2}};
            case 2 -> new float[][]{{x1, y2, z2}, {x2, y2, z2}, {x2, y1, z2}, {x1, y1, z2}};
            case 3 -> new float[][]{{x1, y2, z1}, {x1, y2, z2}, {x1, y1, z2}, {x1, y1, z1}};
            case 4 -> new float[][]{{x1, y2, z1}, {x2, y2, z1}, {x2, y2, z2}, {x1, y2, z2}};
            default -> new float[][]{{x1, y1, z2}, {x2, y1, z2}, {x2, y1, z1}, {x1, y1, z1}};
        };
        Vector3f[] corners = new Vector3f[4];
        for (int i = 0; i < 4; i++) {
            corners[i] = matrix.transformPosition(new Vector3f(c[i][0], c[i][1], c[i][2]));
        }
        Vector3f local = switch (face) {
            case 0 -> new Vector3f(0, 0, -1);
            case 1 -> new Vector3f(1, 0, 0);
            case 2 -> new Vector3f(0, 0, 1);
            case 3 -> new Vector3f(-1, 0, 0);
            case 4 -> new Vector3f(0, 1, 0);
            default -> new Vector3f(0, -1, 0);
        };
        Vector3f normal = matrix.transformDirection(local).normalize();
        // UV corners top-left, top-right, bottom-right, bottom-left; a face rotation turns the image clockwise in 90 degree steps.
        float[][] uvCorners = {{uv.u1(), uv.v1()}, {uv.u2(), uv.v1()}, {uv.u2(), uv.v2()}, {uv.u1(), uv.v2()}};
        int shift = Math.floorMod(uv.rotation() / 90, 4);
        float[] uvs = new float[8];
        for (int i = 0; i < 4; i++) {
            float[] corner = uvCorners[Math.floorMod(i - shift, 4)];
            uvs[i * 2] = corner[0];
            uvs[i * 2 + 1] = corner[1];
        }
        // submit order: top-left, bottom-left, bottom-right, top-right (counter-clockwise seen from outside)
        int[] order = {0, 3, 2, 1};
        Vector3f[] orderedCorners = new Vector3f[4];
        float[] orderedUv = new float[8];
        for (int i = 0; i < 4; i++) {
            orderedCorners[i] = corners[order[i]];
            orderedUv[i * 2] = uvs[order[i] * 2];
            orderedUv[i * 2 + 1] = uvs[order[i] * 2 + 1];
        }
        return new Quad(uv.texture(), orderedCorners, normal, orderedUv);
    }
}
